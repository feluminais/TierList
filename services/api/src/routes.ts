import { isStorableText, migrate, sameDocument, validateDocument, type TierList } from "@tl/core";
import { Hono } from "hono";
import { bodyLimit } from "hono/body-limit";
import { createHash, randomUUID } from "node:crypto";
import { requireOwner, type AuthVars } from "./auth";
import { sniffImage } from "./image";
import { RevisionConflictError, type Repository } from "./repository";
import type { AssetRow } from "./schema";
import { generateShareCode, isPlausibleShareCode } from "./sharecode";
import type { ObjectStore } from "./store";
import { generateToken, hashToken } from "./tokens";

export interface RouteDeps {
  repository: Repository;
  store: ObjectStore;
  /**
   * The server's clock: every timestamp this service records comes from here.
   * Injected so a test can order writes deterministically.
   */
  now?: () => Date;
}

/**
 * Ceilings on what a request may send, enforced while the body streams in —
 * before any of it is buffered — so an oversized request costs at most this
 * much memory and is refused with 413. A `Content-Length` over the limit is
 * refused without reading anything.
 *
 * An upload needs its complete bytes (`sniffImage` and the checksum both read
 * the whole file), which is why its limit is the one that matters most. A
 * document's limit sits far above any list the editor produces; the per-field
 * limits in `validateDocument` bound what a document may contain, and this
 * bounds how much text a request may spend saying it.
 */
const MAX_UPLOAD_BYTES = 10 * 1024 * 1024;
const MAX_DOCUMENT_BYTES = 5 * 1024 * 1024;
const MAX_SMALL_BODY_BYTES = 16 * 1024;

/** Why a share may be reported. A closed set, so an operator can sort by it. */
export const REPORT_REASONS = ["illegal", "abuse", "copyright", "spam", "other"] as const;
export type ReportReason = (typeof REPORT_REASONS)[number];
const MAX_REPORT_NOTE_LENGTH = 500;

function limitBody(maxSize: number) {
  return bodyLimit({ maxSize, onError: (c) => c.json({ error: "too large" }, 413) });
}

/**
 * Bounds on a browse request, so a public unauthenticated endpoint cannot be
 * asked for the whole table, or for a search term long enough to be a payload
 * in its own right.
 */
const DEFAULT_BROWSE_LIMIT = 48;
const MAX_BROWSE_LIMIT = 96;
const MAX_SEARCH_LENGTH = 80;

/**
 * Cheap shape check so an id that cannot possibly name a row never reaches
 * the database — the same reasoning as `isValidTokenFormat` in tokens.ts and
 * `SAFE_KEY` in store.ts, applied to asset ids. This is deliberately not "is
 * this a UUID": the id column is plain text with no format constraint of its
 * own (a row can carry any text — see the "orphan" fixture in
 * assets.test.ts), so a real lookup still has to run for anything shaped
 * like a normal id, and this must not steal that path.
 *
 * It rejects only what Postgres itself cannot hold, the same check every value
 * from a URL has before it reaches a query: Postgres refuses a NUL with error
 * 22021, and left uncaught that reaches the client as a bare 500 —
 * indistinguishable from the database actually being broken, which is exactly
 * the signal a genuine outage needs and must not be blunted. The length bound
 * is the same idea applied to a request that could otherwise spend a full round
 * trip on a string long enough that it could never have been generated by this
 * service.
 */
const MAX_ASSET_ID_LENGTH = 256;
function isPlausibleAssetId(id: string): boolean {
  return id.length > 0 && id.length <= MAX_ASSET_ID_LENGTH && isStorableText(id);
}

/** What an upload answers with: the asset's id and what its bytes are. */
function assetBody(row: AssetRow) {
  return {
    id: row.id,
    contentType: row.contentType,
    width: row.width,
    height: row.height,
    byteSize: row.byteSize,
  };
}

/** A parsed document, or the reasons it was refused. */
type ParseResult =
  | { ok: true; doc: TierList }
  | { ok: false; problems: string[] };

/**
 * Turn an untrusted body into a document, in the two steps @tl/core defines:
 * `migrate` brings it to the current schema, `validateDocument` checks it
 * against the model's structural rules.
 *
 * Both are needed. Migration is deliberately tolerant of fields it cannot make
 * sense of, so it alone would let a document through carrying a title that is
 * not a string or a timestamp that is not a date — values this service then
 * projects into typed database columns, where they fail as a server error
 * rather than as the client error they are.
 */
function parseDocument(value: unknown): ParseResult {
  let migrated: unknown;
  try {
    migrated = migrate(value);
  } catch (e) {
    return { ok: false, problems: [e instanceof Error ? e.message : "unreadable document"] };
  }

  const problems = validateDocument(migrated);
  if (problems.length > 0) return { ok: false, problems };
  return { ok: true, doc: migrated as TierList };
}

export function createRoutes(deps: RouteDeps) {
  const routes = new Hono<AuthVars>();
  const now = deps.now ?? (() => new Date());

  /**
   * The server mints a token's identity itself. The document model forbids
   * generating ids so reductions stay deterministic, but a token has no such
   * requirement and no caller should be choosing its own identity.
   */
  routes.post("/tokens", async (c) => {
    const token = generateToken();
    const id = randomUUID();
    await deps.repository.createToken(id, hashToken(token), now());
    return c.json({ id, token }, 201);
  });

  /** Scoped to the caller. Registered before `/lists/:id` for readability; the
   * two patterns do not overlap, so order does not affect matching. */
  routes.get("/lists", requireOwner(deps.repository), async (c) => {
    const lists = await deps.repository.listByOwner(c.get("ownerId"));
    return c.json({ lists });
  });

  routes.put("/lists/:id", limitBody(MAX_DOCUMENT_BYTES), requireOwner(deps.repository), async (c) => {
    const id = c.req.param("id");
    const body = await c.req.json().catch(() => null);
    const parsed = parseDocument((body as { document?: unknown })?.document);

    if (!parsed.ok) {
      return c.json({ error: "invalid document", problems: parsed.problems }, 400);
    }
    const doc = parsed.doc;
    if (doc.id !== id) return c.json({ error: "id mismatch" }, 400);

    const ownerId = c.get("ownerId");
    const created = await deps.repository.create(doc, ownerId, now());
    if (!created) {
      // A repeat of a create that already succeeded — the client never saw
      // the response and sent it again — is answered as the first one was.
      // Anything else under this id is a genuine collision.
      const replay =
        (await deps.repository.findOwner(id)) === ownerId &&
        sameDocument((await deps.repository.load(id))!, doc);
      if (!replay) return c.json({ error: "already exists" }, 409);
    }
    return c.json({ id: doc.id, revision: doc.revision }, 201);
  });

  // Deliberately unauthenticated: sharing a link to a tier list is the point.
  routes.get("/lists/:id", async (c) => {
    const id = c.req.param("id");
    if (!id || !isStorableText(id)) return c.json({ error: "not found" }, 404);

    const doc = await deps.repository.load(id);
    if (!doc) return c.json({ error: "not found" }, 404);
    return c.json({ document: doc });
  });

  routes.patch("/lists/:id", limitBody(MAX_DOCUMENT_BYTES), requireOwner(deps.repository), async (c) => {
    const id = c.req.param("id");
    const body = (await c.req.json().catch(() => null)) as {
      document?: unknown;
      expectedRevision?: unknown;
    } | null;

    const parsed = parseDocument(body?.document);
    const expected = body?.expectedRevision;

    if (!parsed.ok) {
      return c.json({ error: "invalid document", problems: parsed.problems }, 400);
    }
    const doc = parsed.doc;
    if (doc.id !== id) return c.json({ error: "id mismatch" }, 400);
    if (typeof expected !== "number") {
      return c.json({ error: "expectedRevision is required" }, 400);
    }

    const ownerId = c.get("ownerId");
    const currentOwner = await deps.repository.findOwner(id);

    // Unknown id and someone else's id are deliberately the same response:
    // telling a stranger that an id exists is a small information leak, and
    // no legitimate client needs the distinction.
    //
    // Checking here rather than relying on update() failing is what keeps 404
    // and 409 apart. There is a benign race — ownership could change between
    // this check and the update, and the update would then 409 at someone who
    // no longer owns the document. Nothing transfers ownership today, so it
    // cannot happen; if transfer is ever added the cost is a spurious retry,
    // not unauthorised access.
    if (currentOwner === null || currentOwner !== ownerId) {
      return c.json({ error: "not found" }, 404);
    }

    try {
      await deps.repository.update(doc, expected, ownerId, now());
    } catch (e) {
      if (!(e instanceof RevisionConflictError)) throw e;

      // A write that already landed and is being sent again — its response
      // was lost, so the client retries with the revision it expected the
      // first time — finds the store already holding exactly this document.
      // That is success, not a conflict: answering 409 would stop a client's
      // saving for good over a response that merely went missing.
      const stored = await deps.repository.load(id);
      if (stored && sameDocument(stored, doc)) {
        return c.json({ id: doc.id, revision: doc.revision });
      }

      // Ownership is already established, so this can only be a stale
      // revision. 409 tells the client to re-read and retry.
      return c.json({ error: "revision conflict" }, 409);
    }

    return c.json({ id: doc.id, revision: doc.revision });
  });

  /**
   * Removes a list and what only it used: its share and the images no other
   * document or share preview refers to. Unknown id and someone else's id give
   * the same 404, as PATCH and share do, so this cannot be used to learn which
   * ids exist.
   *
   * The database is the truth and is changed first, in one transaction; the
   * bytes of the images it removed are deleted afterwards and a failure there
   * is only an unreferenced object left behind, which nothing can read.
   */
  routes.delete("/lists/:id", requireOwner(deps.repository), async (c) => {
    const id = c.req.param("id");
    if (!id || !isStorableText(id)) return c.json({ error: "not found" }, 404);

    const result = await deps.repository.deleteList(id, c.get("ownerId"));
    if (!result) return c.json({ error: "not found" }, 404);

    await Promise.all(
      result.removedAssets.map((asset) => deps.store.delete(asset.storageKey).catch(() => undefined)),
    );
    return c.body(null, 204);
  });

  routes.post("/assets", limitBody(MAX_UPLOAD_BYTES), requireOwner(deps.repository), async (c) => {
    const body = new Uint8Array(await c.req.arrayBuffer());

    // The sole authority on what an upload is. The request's own content-type
    // is deliberately never read: it is a claim by the uploader, and trusting
    // it would let a caller store anything under an image's name.
    const info = sniffImage(body);
    if (!info) return c.json({ error: "unsupported image" }, 415);

    const ownerId = c.get("ownerId");
    const checksum = createHash("sha256").update(body).digest("hex");

    // Adding the same picture to a list twice is ordinary. Returning the asset
    // the owner already has costs one lookup and saves a second copy.
    const existing = await deps.repository.findAssetByChecksum(ownerId, checksum);
    if (existing) return c.json(assetBody(existing), 200);

    const id = randomUUID();
    const storageKey = `assets/${id}`;

    // Bytes first: an asset row pointing at a key with nothing behind it would
    // render as a permanently broken tile, whereas an orphaned object is
    // invisible and costs only space.
    await deps.store.put(storageKey, body, info.contentType);
    const created = await deps.repository.createAsset({
      id,
      ownerId,
      storageKey,
      contentType: info.contentType,
      byteSize: body.byteLength,
      width: info.width,
      height: info.height,
      checksum,
      createdAt: now(),
    });

    if (!created) {
      // A concurrent upload of the same bytes by this owner got its row in
      // first. Those bytes are what the winner's asset serves; ours are an
      // unreferenced copy, removed so they cost nothing.
      await deps.store.delete(storageKey).catch(() => undefined);
      const winner = await deps.repository.findAssetByChecksum(ownerId, checksum);
      if (!winner) return c.json({ error: "upload raced, retry" }, 409);
      return c.json(assetBody(winner), 200);
    }

    return c.json(
      {
        id,
        contentType: info.contentType,
        width: info.width,
        height: info.height,
        byteSize: body.byteLength,
      },
      201,
    );
  });

  /**
   * Deliberately unauthenticated, for the same reason `GET /lists/:id` is: an
   * asset referenced by a public document has to be publicly readable, or every
   * shared list renders as broken images.
   */
  routes.get("/assets/:id", async (c) => {
    const id = c.req.param("id");
    if (!isPlausibleAssetId(id)) return c.json({ error: "not found" }, 404);

    const row = await deps.repository.findAsset(id);
    if (!row) return c.json({ error: "not found" }, 404);

    const object = await deps.store.get(row.storageKey);
    // A row without bytes is a broken invariant, not a client error — uploads
    // write bytes before the row. Reporting 404 keeps a torn write from
    // presenting as a 500 to every viewer of a shared list.
    if (!object) return c.json({ error: "not found" }, 404);

    // A plain Response rather than `c.body`: a Uint8Array is already a valid
    // BodyInit, and going through Hono's helper only adds a cast to satisfy its
    // narrower parameter type.
    return new Response(object.bytes, {
      status: 200,
      headers: {
        "content-type": object.contentType,
        "content-length": String(object.bytes.byteLength),
        // An asset id names one immutable byte string for good — nothing ever
        // rewrites a storage key — so a cache never needs to revalidate.
        "cache-control": "public, max-age=31536000, immutable",
      },
    });
  });

  /**
   * Create — or return — the public link for a list.
   *
   * Idempotent by design: a list has at most one code for its whole life, so a
   * second call gets the first call's code back rather than a new one. A link
   * that has been pasted into a chat has to keep working, and two live codes
   * for one list would mean the OG image cached against one of them is
   * silently not the one a reader gets.
   *
   * `ogAssetId` names an ordinary asset the *client* uploaded, rather than an
   * image this service renders. The design doc specifies a server-side render
   * reusing the editor's own path headlessly; this deviates from it because
   * `@tl/editor` is a React and react-native-skia component tree with no
   * headless renderer in Node, so a server-side version would be a second
   * drawing implementation over raw canvaskit — two implementations that can
   * disagree about the same picture. Snapshotting the editor's live canvas
   * makes the preview and the board the same pixels, and the result lands in
   * the public, immutable asset path a tile image already uses.
   *
   * The cost is that a client which cannot snapshot produces a link with a
   * title and no picture.
   */
  routes.post("/lists/:id/share", limitBody(MAX_SMALL_BODY_BYTES), requireOwner(deps.repository), async (c) => {
    // Hono types this as possibly undefined for a path with a segment *after*
    // the parameter (`/lists/:id/share`), unlike `/lists/:id`. It cannot
    // actually be undefined — the route would not have matched — but the guard
    // is a real answer rather than a cast, and 404 is what an empty id would
    // have produced two lines later anyway.
    const listId = c.req.param("id");
    if (!listId || !isStorableText(listId)) return c.json({ error: "not found" }, 404);

    const ownerId = c.get("ownerId");
    const body = (await c.req.json().catch(() => null)) as { ogAssetId?: unknown; listed?: unknown } | null;

    const ogAssetId =
      typeof body?.ogAssetId === "string" && isPlausibleAssetId(body.ogAssetId)
        ? body.ogAssetId
        : null;
    // Absent means "leave it as it is". Listing is a separate decision from
    // sharing, and a client that only wanted a link must not silently
    // unlist a share the author had already published.
    const listed = typeof body?.listed === "boolean" ? body.listed : null;

    // Unknown id and someone else's id give the same answer, exactly as PATCH
    // does: telling a stranger which list ids exist is a leak no legitimate
    // client needs.
    const currentOwner = await deps.repository.findOwner(listId);
    if (currentOwner === null || currentOwner !== ownerId) {
      return c.json({ error: "not found" }, 404);
    }

    // An id that names no asset would become an `og:image` URL that 404s, so
    // the share is refused rather than created with a preview that cannot
    // load. Checked after ownership, so it cannot be used to probe which
    // asset ids exist.
    if (ogAssetId && !(await deps.repository.findAsset(ogAssetId))) {
      return c.json({ error: "unknown ogAssetId" }, 400);
    }

    const existing = await deps.repository.findShareByList(listId);
    if (existing) {
      if (ogAssetId && ogAssetId !== existing.ogAssetId) {
        await deps.repository.setShareOgAsset(existing.code, ogAssetId);
      }
      if (listed !== null && listed !== existing.listed) {
        await deps.repository.setShareListed(existing.code, listed);
      }
      return c.json(
        {
          code: existing.code,
          ogAssetId: ogAssetId ?? existing.ogAssetId,
          listed: listed ?? existing.listed,
        },
        200,
      );
    }

    // A collision is a lost race, not an error: 40 bits of code space makes it
    // vanishingly rare, and retrying is cheaper than reporting a failure the
    // caller can do nothing about. Bounded so a genuinely broken generator
    // (one returning a constant, say) surfaces as a 500 rather than spinning.
    for (let attempt = 0; attempt < 5; attempt++) {
      const code = generateShareCode();
      const claimed = await deps.repository.createShare({
        code,
        listId,
        ownerId,
        ogAssetId,
        listed: listed ?? false,
        createdAt: now(),
      });
      if (claimed) return c.json({ code, ogAssetId, listed: listed ?? false }, 201);
    }
    return c.json({ error: "could not allocate a share code" }, 500);
  });

  /**
   * Withdraws a list's public link and its listing. The list itself is
   * untouched, and sharing it again mints a new code: the old one stays dead,
   * which is what withdrawing a link means.
   */
  routes.delete("/lists/:id/share", requireOwner(deps.repository), async (c) => {
    const id = c.req.param("id");
    if (!id || !isStorableText(id)) return c.json({ error: "not found" }, 404);

    const removed = await deps.repository.deleteShareOfList(id, c.get("ownerId"));
    if (!removed) return c.json({ error: "not found" }, 404);
    return c.body(null, 204);
  });

  /**
   * Anyone holding a share's link may report it; no token is needed, because
   * the people who run into content that should not be public are the people
   * who were sent a link. A report only records. Acting on it is an operator's
   * decision, made from the database.
   */
  routes.post("/reports", limitBody(MAX_SMALL_BODY_BYTES), async (c) => {
    const body = (await c.req.json().catch(() => null)) as {
      code?: unknown;
      reason?: unknown;
      note?: unknown;
    } | null;
    if (!body || typeof body !== "object") return c.json({ error: "invalid report" }, 400);

    const { code, reason, note } = body;
    if (typeof code !== "string") return c.json({ error: "code is required" }, 400);
    if (typeof reason !== "string" || !(REPORT_REASONS as readonly string[]).includes(reason)) {
      return c.json({ error: "unknown reason" }, 400);
    }
    if (
      note !== undefined &&
      note !== null &&
      (typeof note !== "string" || note.length > MAX_REPORT_NOTE_LENGTH || !isStorableText(note))
    ) {
      return c.json({ error: "invalid note" }, 400);
    }

    // Checked after the body, so a report that is malformed is a 400 whether
    // or not the code exists.
    if (!isPlausibleShareCode(code) || !(await deps.repository.findShareByCode(code))) {
      return c.json({ error: "not found" }, 404);
    }

    const id = randomUUID();
    await deps.repository.createReport({
      id,
      shareCode: code,
      reason,
      note: typeof note === "string" && note.length > 0 ? note : null,
      createdAt: now(),
    });
    return c.json({ id }, 201);
  });

  /**
   * Read a shared list by its code. Deliberately unauthenticated — the whole
   * point of a share code is that holding it is the authorisation.
   *
   * The document carries its own `id`, so a reader does learn the list id.
   * That grants nothing a share does not: `GET /lists/:id` is public and
   * returns the same document, and every write requires the owner's token.
   */
  routes.get("/shares/:code", async (c) => {
    const code = c.req.param("code");
    if (!isPlausibleShareCode(code)) return c.json({ error: "not found" }, 404);

    const share = await deps.repository.findShareByCode(code);
    if (!share) return c.json({ error: "not found" }, 404);

    const doc = await deps.repository.load(share.listId);
    // A share whose list has gone is a dead link, not a server fault.
    if (!doc) return c.json({ error: "not found" }, 404);

    /**
     * The intrinsic size of every image the document references.
     *
     * Not a nicety. A public page renders the board as HTML without decoding
     * anything — that is what keeps CanvasKit off the critical path — and a
     * crop is stored as a *fraction of the source*, so which pixels a tile
     * shows depends on the source's own aspect ratio. Without these the page
     * can only fall back to a plain centred cover, which is a different
     * picture from the one the author framed. The editor never needs them
     * because it has the decoded image in hand.
     */
    const assetIds = [
      ...new Set(doc.items.map((i) => i.assetId).filter((a): a is string => !!a)),
    ];
    const assets = await deps.repository.findAssetSizes(assetIds);

    return c.json({
      document: doc,
      ogAssetId: share.ogAssetId,
      listed: share.listed,
      assets,
    });
  });

  /**
   * Publicly listed shares.
   *
   * Unauthenticated, and deliberately narrow: it returns the projected columns
   * a grid needs and never a document. Browsing is not reading — a reader who
   * wants the list follows the code to `GET /shares/:code`, which is the one
   * place a document is served from.
   *
   * Only shares whose author opted in appear. Holding a link and being indexed
   * are different offers, and the second is asked for rather than assumed.
   */
  routes.get("/browse", async (c) => {
    const category = c.req.query("category");
    const text = c.req.query("q");
    const requested = Number.parseInt(c.req.query("limit") ?? "", 10);

    // Text the database cannot hold cannot match anything it holds, so this is
    // an empty result rather than a query for Postgres to refuse.
    if (!isStorableText(category ?? "") || !isStorableText(text ?? "")) {
      return c.json({ results: [] });
    }

    const results = await deps.repository.browse({
      // An unknown category is not an error and not "everything": it is a
      // category with nothing in it, which is what an empty result says.
      categoryId: category ? category : null,
      text: text ? text.slice(0, MAX_SEARCH_LENGTH) : null,
      limit: Number.isFinite(requested)
        ? Math.min(Math.max(requested, 1), MAX_BROWSE_LIMIT)
        : DEFAULT_BROWSE_LIMIT,
    });

    return c.json({
      results: results.map((r) => ({
        code: r.code,
        title: r.title,
        categoryId: r.categoryId,
        ogAssetId: r.ogAssetId,
        updatedAt: r.updatedAt.toISOString(),
      })),
    });
  });

  return routes;
}
