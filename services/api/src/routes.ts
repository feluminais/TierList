import { migrate, validateDocument, type TierList } from "@tl/core";
import { Hono } from "hono";
import { createHash, randomUUID } from "node:crypto";
import { requireOwner, type AuthVars } from "./auth";
import { sniffImage } from "./image";
import { RevisionConflictError, type Repository } from "./repository";
import { generateShareCode, isPlausibleShareCode } from "./sharecode";
import type { ObjectStore } from "./store";
import { generateToken, hashToken } from "./tokens";

export interface RouteDeps {
  repository: Repository;
  store: ObjectStore;
}

/**
 * A ceiling on what gets *stored*, not on what gets received. The body is
 * buffered whole before this check runs — `sniffImage` and the checksum both
 * need the complete bytes — so a larger request still costs the memory to
 * receive in full, and this only stops the result being written to the object
 * store. Bounding the received size needs a limit enforced before buffering,
 * which nothing wires up; that gap belongs with the deploy.
 */
const MAX_UPLOAD_BYTES = 10 * 1024 * 1024;

/**
 * Cheap shape check so an id that cannot possibly name a row never reaches
 * the database — the same reasoning as `isValidTokenFormat` in tokens.ts and
 * `SAFE_KEY` in store.ts, applied to asset ids. This is deliberately not "is
 * this a UUID": the id column is plain text with no format constraint of its
 * own (a row can carry any text — see the "orphan" fixture in
 * assets.test.ts), so a real lookup still has to run for anything shaped
 * like a normal id, and this must not steal that path.
 *
 * It rejects only what Postgres itself cannot hold: a NUL byte is not valid
 * inside a text value to libpq, which raises "invalid byte sequence for
 * encoding "UTF8"" (error 22021). Left uncaught, that reaches the client as a
 * bare 500 — indistinguishable from the database actually being broken,
 * which is exactly the signal a genuine outage needs and must not be
 * blunted. The length bound is the same idea applied to a request that could
 * otherwise spend a full round trip on a string long enough that it could
 * never have been generated by this service.
 */
const MAX_ASSET_ID_LENGTH = 256;
function isPlausibleAssetId(id: string): boolean {
  return id.length > 0 && id.length <= MAX_ASSET_ID_LENGTH && !id.includes("\0");
}

/** A parsed document, or the reasons it was refused. */
type ParseResult =
  | { ok: true; doc: TierList }
  | { ok: false; problems: string[] };

/**
 * Turn an untrusted body into a document, in the two steps @tl/core defines:
 * `migrate` brings it to the current schema, `validateDocument` checks it
 * against the model's structural rules.
 *
 * Both are needed. Migration is deliberately tolerant of fields it cannot make
 * sense of, so it alone would let a document through carrying a title that is
 * not a string or a timestamp that is not a date — values this service then
 * projects into typed database columns, where they fail as a server error
 * rather than as the client error they are.
 */
function parseDocument(value: unknown): ParseResult {
  let migrated: unknown;
  try {
    migrated = migrate(value);
  } catch (e) {
    return { ok: false, problems: [e instanceof Error ? e.message : "unreadable document"] };
  }

  const problems = validateDocument(migrated);
  if (problems.length > 0) return { ok: false, problems };
  return { ok: true, doc: migrated as TierList };
}

export function createRoutes(deps: RouteDeps) {
  const routes = new Hono<AuthVars>();

  /**
   * The one place the server generates an id and reads the clock. The document
   * model forbids both so reductions stay deterministic, but a token has no
   * such requirement and no caller should be choosing its own identity.
   */
  routes.post("/tokens", async (c) => {
    const token = generateToken();
    const id = randomUUID();
    await deps.repository.createToken(id, hashToken(token), new Date());
    return c.json({ id, token }, 201);
  });

  /** Scoped to the caller. Registered before `/lists/:id` for readability; the
   * two patterns do not overlap, so order does not affect matching. */
  routes.get("/lists", requireOwner(deps.repository), async (c) => {
    const lists = await deps.repository.listByOwner(c.get("ownerId"));
    return c.json({ lists });
  });

  routes.put("/lists/:id", requireOwner(deps.repository), async (c) => {
    const id = c.req.param("id");
    const body = await c.req.json().catch(() => null);
    const parsed = parseDocument((body as { document?: unknown })?.document);

    if (!parsed.ok) {
      return c.json({ error: "invalid document", problems: parsed.problems }, 400);
    }
    const doc = parsed.doc;
    if (doc.id !== id) return c.json({ error: "id mismatch" }, 400);

    const created = await deps.repository.create(doc, c.get("ownerId"));
    if (!created) return c.json({ error: "already exists" }, 409);
    return c.json({ id: doc.id, revision: doc.revision }, 201);
  });

  // Deliberately unauthenticated: sharing a link to a tier list is the point.
  routes.get("/lists/:id", async (c) => {
    const doc = await deps.repository.load(c.req.param("id"));
    if (!doc) return c.json({ error: "not found" }, 404);
    return c.json({ document: doc });
  });

  routes.patch("/lists/:id", requireOwner(deps.repository), async (c) => {
    const id = c.req.param("id");
    const body = (await c.req.json().catch(() => null)) as {
      document?: unknown;
      expectedRevision?: unknown;
    } | null;

    const parsed = parseDocument(body?.document);
    const expected = body?.expectedRevision;

    if (!parsed.ok) {
      return c.json({ error: "invalid document", problems: parsed.problems }, 400);
    }
    const doc = parsed.doc;
    if (doc.id !== id) return c.json({ error: "id mismatch" }, 400);
    if (typeof expected !== "number") {
      return c.json({ error: "expectedRevision is required" }, 400);
    }

    const ownerId = c.get("ownerId");
    const currentOwner = await deps.repository.findOwner(id);

    // Unknown id and someone else's id are deliberately the same response:
    // telling a stranger that an id exists is a small information leak, and
    // no legitimate client needs the distinction.
    //
    // Checking here rather than relying on update() failing is what keeps 404
    // and 409 apart. There is a benign race — ownership could change between
    // this check and the update, and the update would then 409 at someone who
    // no longer owns the document. Nothing transfers ownership today, so it
    // cannot happen; if transfer is ever added the cost is a spurious retry,
    // not unauthorised access.
    if (currentOwner === null || currentOwner !== ownerId) {
      return c.json({ error: "not found" }, 404);
    }

    try {
      await deps.repository.update(doc, expected, ownerId);
    } catch (e) {
      if (e instanceof RevisionConflictError) {
        // Ownership is already established, so this can only be a stale
        // revision. 409 tells the client to re-read and retry.
        return c.json({ error: "revision conflict" }, 409);
      }
      throw e;
    }

    return c.json({ id: doc.id, revision: doc.revision });
  });

  routes.post("/assets", requireOwner(deps.repository), async (c) => {
    const body = new Uint8Array(await c.req.arrayBuffer());

    // Checked after buffering rather than from the Content-Length header,
    // because a header is a claim and a chunked request need not send one.
    if (body.byteLength > MAX_UPLOAD_BYTES) {
      return c.json({ error: "too large" }, 413);
    }

    // The sole authority on what an upload is. The request's own content-type
    // is deliberately never read: it is a claim by the uploader, and trusting
    // it would let a caller store anything under an image's name.
    const info = sniffImage(body);
    if (!info) return c.json({ error: "unsupported image" }, 415);

    const ownerId = c.get("ownerId");
    const checksum = createHash("sha256").update(body).digest("hex");

    // Adding the same picture to a list twice is ordinary. Returning the asset
    // the owner already has costs one lookup and saves a second copy.
    const existing = await deps.repository.findAssetByChecksum(ownerId, checksum);
    if (existing) {
      return c.json(
        {
          id: existing.id,
          contentType: existing.contentType,
          width: existing.width,
          height: existing.height,
          byteSize: existing.byteSize,
        },
        200,
      );
    }

    const id = randomUUID();
    const storageKey = `assets/${id}`;

    // Bytes first: an asset row pointing at a key with nothing behind it would
    // render as a permanently broken tile, whereas an orphaned object is
    // invisible and costs only space.
    await deps.store.put(storageKey, body, info.contentType);
    await deps.repository.createAsset({
      id,
      ownerId,
      storageKey,
      contentType: info.contentType,
      byteSize: body.byteLength,
      width: info.width,
      height: info.height,
      checksum,
      createdAt: new Date(),
    });

    return c.json(
      {
        id,
        contentType: info.contentType,
        width: info.width,
        height: info.height,
        byteSize: body.byteLength,
      },
      201,
    );
  });

  /**
   * Deliberately unauthenticated, for the same reason `GET /lists/:id` is: an
   * asset referenced by a public document has to be publicly readable, or every
   * shared list renders as broken images.
   */
  routes.get("/assets/:id", async (c) => {
    const id = c.req.param("id");
    if (!isPlausibleAssetId(id)) return c.json({ error: "not found" }, 404);

    const row = await deps.repository.findAsset(id);
    if (!row) return c.json({ error: "not found" }, 404);

    const object = await deps.store.get(row.storageKey);
    // A row without bytes is a broken invariant, not a client error — uploads
    // write bytes before the row. Reporting 404 keeps a torn write from
    // presenting as a 500 to every viewer of a shared list.
    if (!object) return c.json({ error: "not found" }, 404);

    // A plain Response rather than `c.body`: a Uint8Array is already a valid
    // BodyInit, and going through Hono's helper only adds a cast to satisfy its
    // narrower parameter type.
    return new Response(object.bytes, {
      status: 200,
      headers: {
        "content-type": object.contentType,
        "content-length": String(object.bytes.byteLength),
        // An asset id names one immutable byte string for good — nothing ever
        // rewrites a storage key — so a cache never needs to revalidate.
        "cache-control": "public, max-age=31536000, immutable",
      },
    });
  });

  /**
   * Create — or return — the public link for a list.
   *
   * Idempotent by design: a list has at most one code for its whole life, so a
   * second call gets the first call's code back rather than a new one. A link
   * that has been pasted into a chat has to keep working, and two live codes
   * for one list would mean the OG image cached against one of them is
   * silently not the one a reader gets.
   *
   * `ogAssetId` names an ordinary asset the *client* uploaded, rather than an
   * image this service renders. The design doc specifies a server-side render
   * reusing the editor's own path headlessly; this deviates from it because
   * `@tl/editor` is a React and react-native-skia component tree with no
   * headless renderer in Node, so a server-side version would be a second
   * drawing implementation over raw canvaskit — two implementations that can
   * disagree about the same picture. Snapshotting the editor's live canvas
   * makes the preview and the board the same pixels, and the result lands in
   * the public, immutable asset path a tile image already uses.
   *
   * The cost is that a client which cannot snapshot produces a link with a
   * title and no picture.
   */
  routes.post("/lists/:id/share", requireOwner(deps.repository), async (c) => {
    // Hono types this as possibly undefined for a path with a segment *after*
    // the parameter (`/lists/:id/share`), unlike `/lists/:id`. It cannot
    // actually be undefined — the route would not have matched — but the guard
    // is a real answer rather than a cast, and 404 is what an empty id would
    // have produced two lines later anyway.
    const listId = c.req.param("id");
    if (!listId) return c.json({ error: "not found" }, 404);

    const ownerId = c.get("ownerId");
    const body = (await c.req.json().catch(() => null)) as { ogAssetId?: unknown } | null;

    const ogAssetId =
      typeof body?.ogAssetId === "string" && isPlausibleAssetId(body.ogAssetId)
        ? body.ogAssetId
        : null;

    // Unknown id and someone else's id give the same answer, exactly as PATCH
    // does: telling a stranger which list ids exist is a leak no legitimate
    // client needs.
    const currentOwner = await deps.repository.findOwner(listId);
    if (currentOwner === null || currentOwner !== ownerId) {
      return c.json({ error: "not found" }, 404);
    }

    // An id that names no asset would become an `og:image` URL that 404s, so
    // the share is refused rather than created with a preview that cannot
    // load. Checked after ownership, so it cannot be used to probe which
    // asset ids exist.
    if (ogAssetId && !(await deps.repository.findAsset(ogAssetId))) {
      return c.json({ error: "unknown ogAssetId" }, 400);
    }

    const existing = await deps.repository.findShareByList(listId);
    if (existing) {
      if (ogAssetId && ogAssetId !== existing.ogAssetId) {
        await deps.repository.setShareOgAsset(existing.code, ogAssetId);
      }
      return c.json({ code: existing.code, ogAssetId: ogAssetId ?? existing.ogAssetId }, 200);
    }

    // A collision is a lost race, not an error: 40 bits of code space makes it
    // vanishingly rare, and retrying is cheaper than reporting a failure the
    // caller can do nothing about. Bounded so a genuinely broken generator
    // (one returning a constant, say) surfaces as a 500 rather than spinning.
    for (let attempt = 0; attempt < 5; attempt++) {
      const code = generateShareCode();
      const claimed = await deps.repository.createShare({
        code,
        listId,
        ownerId,
        ogAssetId,
        createdAt: new Date(),
      });
      if (claimed) return c.json({ code, ogAssetId }, 201);
    }
    return c.json({ error: "could not allocate a share code" }, 500);
  });

  /**
   * Read a shared list by its code. Deliberately unauthenticated — the whole
   * point of a share code is that holding it is the authorisation.
   *
   * Returns the document rather than a redirect to `/lists/:id`, so a reader
   * never learns the list id and cannot use it against the owned endpoints.
   */
  routes.get("/shares/:code", async (c) => {
    const code = c.req.param("code");
    if (!isPlausibleShareCode(code)) return c.json({ error: "not found" }, 404);

    const share = await deps.repository.findShareByCode(code);
    if (!share) return c.json({ error: "not found" }, 404);

    const doc = await deps.repository.load(share.listId);
    // A share whose list has gone is a dead link, not a server fault.
    if (!doc) return c.json({ error: "not found" }, 404);

    /**
     * The intrinsic size of every image the document references.
     *
     * Not a nicety. A public page renders the board as HTML without decoding
     * anything — that is what keeps CanvasKit off the critical path — and a
     * crop is stored as a *fraction of the source*, so which pixels a tile
     * shows depends on the source's own aspect ratio. Without these the page
     * can only fall back to a plain centred cover, which is a different
     * picture from the one the author framed. The editor never needs them
     * because it has the decoded image in hand.
     */
    const assetIds = [
      ...new Set(doc.items.map((i) => i.assetId).filter((a): a is string => !!a)),
    ];
    const assets = await deps.repository.findAssetSizes(assetIds);

    return c.json({ document: doc, ogAssetId: share.ogAssetId, assets });
  });

  return routes;
}
